package main

import (
	"os"

	"github.com/annaxiomm/moa/cpu"
	"github.com/annaxiomm/moa/errors"
	"github.com/annaxiomm/moa/screen"
)

func main() {

	cpu := cpu.InitCpu()
	// STI address, value
	program := []uint8{
		0x10, 0x00, 0x48, 0x00,
		0x13, 0x00, 0xa6, 0x00,

		0x10, 0x00, 0x65, 0x00,
		0x13, 0x00, 0xa6, 0x00,

		0x10, 0x00, 0x6c, 0x00,
		0x13, 0x00, 0xa6, 0x00,
		0x13, 0x00, 0xa6, 0x00,

		0x10, 0x00, 0x6f, 0x00,
		0x13, 0x00, 0xa6, 0x00,

		0x10, 0x00, 0x0a, 0x00,
		0x13, 0x00, 0xa6, 0x00,

		0x01,
	}

	cpu.Load(program)

	screen := screen.New(&cpu)
	if err := screen.Run(); err != nil {
		errors.PrintError(err)
		os.Exit(1)
	}
}
